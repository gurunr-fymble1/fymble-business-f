// Function to filter cities based on search query
export const filterCities = (query) => {
  if (!query || query.trim() === "") {
    return [];
  }

  const searchQuery = query.toLowerCase().trim();
  return INDIAN_CITIES.filter(
    (city) =>
      city.toLowerCase().startsWith(searchQuery) ||
      city.toLowerCase().includes(searchQuery)
  ).slice(0, 10); // Limit to 10 suggestions
};

// Function to filter states based on search query
export const filterStates = (query) => {
  if (!query || query.trim() === "") {
    return [];
  }

  const searchQuery = query.toLowerCase().trim();
  return INDIAN_STATES.filter(
    (state) =>
      state.toLowerCase().startsWith(searchQuery) ||
      state.toLowerCase().includes(searchQuery)
  ).slice(0, 10); // Limit to 10 suggestions
};
